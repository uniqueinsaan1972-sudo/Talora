"""Regenerates content/a1_u1_tests.public.json (no answers, shipped to the browser) and
supabase/migrations/0004_seed_a1_u1.sql (answer keys, server-only) from content/src/a1_u1_tests.json.
Run from the project root: python3 scripts/gen_tests.py"""
import json
q = lambda s: "'" + s.replace("'", "''") + "'"
d = json.load(open("content/src/a1_u1_tests.json")); pub = {"unit": d["unit"], "tests": []}
sql = ["-- GENERATED by scripts/gen_tests.py. Do not edit by hand.", "insert into lesson_catalog(lesson_id,xp) values ('a1-u1-l1',5),('a1-u1-l2',5) on conflict do nothing;"]
for t in d["tests"]:
    req = "array[" + ",".join(q(r) for r in t["requires"]) + "]::text[]" if t.get("requires") else "'{}'"
    sql.append(f"insert into test_catalog(test_id,unit_id,kind,xp,requires) values ({q(t['id'])},{q(d['unit'])},{q(t.get('kind','test'))},{t['xp']},{req}) on conflict do nothing;")
    qs = []
    for x in t["questions"]:
        for a in x["answers"]: sql.append(f"insert into test_keys(test_id,question_id,answer) values ({q(t['id'])},{q(x['id'])},{q(a)}) on conflict do nothing;")
        qs.append({k: v for k, v in x.items() if k != "answers"})
    pub["tests"].append({"id": t["id"], "title": t["title"], "kind": t.get("kind", "test"), "questions": qs})
json.dump(pub, open("content/a1_u1_tests.public.json", "w"), indent=1, ensure_ascii=False)
open("supabase/migrations/0004_seed_a1_u1.sql", "w").write("\n".join(sql) + "\n")
