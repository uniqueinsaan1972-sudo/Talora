"""Generates, from content/src/*_tests.json: public tests without answers (content/<unit>_tests.public.json) and the answer-key SQL.
0004 (A1) was already shipped, so it is not regenerated; A2-C1 go to 0005. Run from project root after scripts/units_a2_c1.py."""
import json
q = lambda s: "'" + s.replace("'", "''") + "'"
PTR = {  # same question shown in Urdu / Hindi script (answers stay English, graded on the server)
 "a1-u1-mega-q1": ("“میں پڑھ رہا ہوں۔” means:", "“मैं पढ़ रहा हूँ।” means:"), "a1-u1-mega-q2": ("“ڈیگورونا اسکول جاتا ہے۔” means:", "“डेगोरुना स्कूल जाता है।” means:"),
 "a2-u1-mega-q1": ("“ڈیگورونا نے کل فٹ بال کھیلا۔” means:", "“डेगोरुना ने कल फुटबॉल खेला।” means:"), "b1-u1-mega-q1": ("“میں نے اپنا کام ختم کر لیا ہے۔” means:", "“मैंने अपना काम खत्म कर लिया है।” means:"),
 "b2-u1-mega-q1": ("“استاد کے آنے سے پہلے ڈیگورونا کام ختم کر چکا تھا۔” means:", "“शिक्षक के आने से पहले डेगोरुना काम खत्म कर चुका था।” means:"), "c1-u1-mega-q1": ("“اگلے جون تک ڈیگورونا کورس مکمل کر چکا ہوگا۔” means:", "“अगले जून तक डेगोरुना कोर्स पूरा कर चुका होगा।” means:")}
ORDER = ["a1-u1", "a2-u1", "b1-u1", "b2-u1", "c1-u1"]; sql = ["-- GENERATED by scripts/gen_tests.py. Do not edit by hand."]
for uid in ORDER:
    f = uid.replace("-", "_"); d = json.load(open(f"content/src/{f}_tests.json")); pub = {"unit": uid, "tests": []}
    new = uid != "a1-u1"
    if new:
        for l in json.load(open(f"content/{f}_lessons.json"))["lessons"]: sql.append(f"insert into lesson_catalog(lesson_id,xp) values ({q(l['id'])},5) on conflict do nothing;")
    for t in d["tests"]:
        if new:
            req = "array[" + ",".join(q(r) for r in t["requires"]) + "]::text[]" if t.get("requires") else "'{}'"
            sql.append(f"insert into test_catalog(test_id,unit_id,kind,xp,requires) values ({q(t['id'])},{q(uid)},{q(t.get('kind','test'))},{t['xp']},{req}) on conflict do nothing;")
        qs = []
        for x in t["questions"]:
            if new:
                for a in x["answers"]: sql.append(f"insert into test_keys(test_id,question_id,answer) values ({q(t['id'])},{q(x['id'])},{q(a)}) on conflict do nothing;")
            y = {k: v for k, v in x.items() if k != "answers"}
            if x["id"] in PTR: y["ptr"] = {"urdu": PTR[x["id"]][0], "hindi": PTR[x["id"]][1]}
            qs.append(y)
        pub["tests"].append({"id": t["id"], "title": t["title"], "kind": t.get("kind", "test"), "questions": qs})
    json.dump(pub, open(f"content/{f}_tests.public.json", "w"), indent=1, ensure_ascii=False)
open("supabase/migrations/0005_seed_a2_c1.sql", "w").write("\n".join(sql) + "\n")
